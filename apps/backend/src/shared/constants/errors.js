/**
 * Get HTTP status for an error code
 * @param {string} errorCode
 * @returns {number}
 */
export function getStatusForErrorCode(errorCode) {
  return ERROR_CODE_STATUS_MAP[errorCode] || 500;
}

/**
 * Create standardized error response
 * @param {string} errorCode
 * @param {string} message
 * @param {object} [details]
 * @returns {object}
 */
export function createErrorResponse(errorCode, message, details = {}) {
  return {
    success: false,
    error: {
      code: errorCode,
      message,
      details,
    },
  };
}

