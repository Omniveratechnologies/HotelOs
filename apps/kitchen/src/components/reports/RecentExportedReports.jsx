import { FiClock, FiDownload } from "react-icons/fi";
import ActionButton from "../ui/button/ActionButton.jsx";
import Pagination from "../ui/Pagination.jsx";
import StatusBadge from "../ui/StatusBadge.jsx";
import {
  FORMAT_META,
  formatDateTime,
  formatRange,
  REPORT_META,
} from "../../utils/exportReport.constants.js";

const EMPTY_ARRAY = [];
const DEFAULT_PAGINATION = { page: 1, limit: 10, pages: 1 };

const RecentExportedReports = ({
  rows = EMPTY_ARRAY,
  loading = false,
  pagination = DEFAULT_PAGINATION,
  onPageChange,
  onDownload,
  downloadingId = null,
  renderActions,
}) => {
  const { page, limit, pages } = pagination;
  const colSpan = renderActions ? 11 : 10;

  return (
    <section className="rounded-xl border border-gray-800 bg-[#0b1117] p-4">
      <div className="mb-4 flex items-center gap-2">
        <FiClock size={15} className="text-gray-400" />
        <h3 className="text-sm font-semibold text-white">
          Recent Exported Reports
        </h3>
      </div>

      <div className="overflow-x-auto">
        <table className="w-full min-w-[960px] text-left text-xs">
          <thead>
            <tr className="border-b border-gray-800 text-gray-500">
              <th className="px-2 py-2 font-medium">#</th>
              <th className="px-2 py-2 font-medium">Report Name</th>
              <th className="px-2 py-2 font-medium">Type</th>
              <th className="px-2 py-2 font-medium">Date Range</th>
              <th className="px-2 py-2 font-medium">Format</th>
              <th className="px-2 py-2 font-medium">Generated On</th>
              <th className="px-2 py-2 font-medium">Generated By</th>
              <th className="px-2 py-2 font-medium">Records</th>
              <th className="px-2 py-2 font-medium">Status</th>
              <th className="px-2 py-2 font-medium">Download</th>
              {renderActions && (
                <th className="px-2 py-2 font-medium">Actions</th>
              )}
            </tr>
          </thead>

          <tbody>
            {loading && rows.length === 0 ? (
              <tr>
                <td
                  colSpan={colSpan}
                  className="py-8 text-center text-gray-500"
                >
                  Loading exports...
                </td>
              </tr>
            ) : rows.length === 0 ? (
              <tr>
                <td
                  colSpan={colSpan}
                  className="py-8 text-center text-gray-500"
                >
                  No exported reports yet.
                </td>
              </tr>
            ) : (
              rows.map((row, index) => {
                const format = FORMAT_META[row.format];
                const FormatIcon = format?.icon;
                const completed = row.status === "COMPLETED";
                const ready = completed && !row.expired;
                const badge = completed && row.expired ? "EXPIRED" : row.status;

                return (
                  <tr
                    key={row.id}
                    className="border-b border-gray-800/60 text-gray-300"
                  >
                    <td className="px-2 py-3 text-gray-500">
                      {(page - 1) * limit + index + 1}
                    </td>
                    <td className="px-2 py-3 font-medium whitespace-nowrap text-white">
                      {row.name}
                    </td>
                    <td className="px-2 py-3 whitespace-nowrap">
                      {REPORT_META[row.type]?.label.replace(" Report", "") ||
                        row.type}
                    </td>
                    <td className="px-2 py-3 whitespace-nowrap">
                      {formatRange(row.dateRange) || "-"}
                    </td>
                    <td className="px-2 py-3">
                      {FormatIcon ? (
                        <FormatIcon
                          size={16}
                          className={format.iconColor}
                          title={format.label}
                        />
                      ) : (
                        row.format
                      )}
                    </td>
                    <td className="px-2 py-3 whitespace-nowrap">
                      {formatDateTime(row.generatedOn)}
                    </td>
                    <td className="px-2 py-3 whitespace-nowrap">
                      {row.generatedBy || "-"}
                    </td>
                    <td className="px-2 py-3">{row.records}</td>
                    <td className="px-2 py-3" title={row.errorMessage || ""}>
                      <StatusBadge status={badge} />
                    </td>
                    <td className="px-2 py-3">
                      <ActionButton
                        variant="outline"
                        icon={<FiDownload size={13} />}
                        onClick={() => onDownload(row)}
                        disabled={!ready || downloadingId === row.id}
                      >
                        {downloadingId === row.id
                          ? "Downloading..."
                          : "Download"}
                      </ActionButton>
                    </td>
                    {renderActions && (
                      <td className="px-2 py-3">{renderActions(row)}</td>
                    )}
                  </tr>
                );
              })
            )}
          </tbody>
        </table>
      </div>

      <Pagination
        currentPage={page}
        totalPages={pages}
        onPageChange={onPageChange}
      />
    </section>
  );
};

export default RecentExportedReports;
